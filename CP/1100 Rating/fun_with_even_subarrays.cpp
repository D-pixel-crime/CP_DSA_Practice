int countBits(int x)
{
    return floor(log2(x)) + 1;
}

void solve()
{
    int n;
    cin >> n;

    vector<int> arr(n);
    for (int i = 0; i < n; i++)
    {
        cin >> arr[i];
    }

    int target = arr[n - 1], i = n - 2, ans = 0;
    while (i >= 0)
    {
        if (arr[i] != target)
        {
            i = n - (2 * (n - 1 - i)) - 1;
            ans++;
        }
        else
            i--;
    }

    cout << ans << endl;
}

int main()
{
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);

    int t = 1;
    cin >> t;
    while (t--)
    {
        solve();
    }

    return 0;
}